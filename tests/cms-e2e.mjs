ok('/blog/ keeps the site header, menu and footer', idx.text.includes('site-header') && idx.text.includes('ftr'), '')
ok('/blog/ has title, description, canonical, OG, blog JSON-LD', /<title>The Journal/.test(idx.text) && idx.text.includes('rel="canonical" href="https://illuszionzmedia.com/blog/"') && idx.text.includes('property="og:title"') && idx.text.includes('"@type":"Blog"') && idx.text.includes('index, follow'))
const post = await get('/blog/welcome-post/')
ok('post page: 200 + custom SEO title + description', post.status === 200 && post.text.includes('<title>Custom SEO Title | Illuszionz</title>') && post.text.includes('content="Custom meta description for the welcome post."'))
ok('post page: canonical + OG article + Twitter card', post.text.includes('rel="canonical" href="https://illuszionzmedia.com/blog/welcome-post/"') && post.text.includes('property="og:type" content="article"') && post.text.includes('article:published_time') && post.text.includes('twitter:card') && post.text.includes('og:image" content="https://illuszionzmedia.com/images/ILU6151.webp"'))
ok('post page: BlogPosting + BreadcrumbList JSON-LD', post.text.includes('"@type":"BlogPosting"') && post.text.includes('"@type":"BreadcrumbList"') && post.text.includes('"headline":"A welcome post about portraits"'))
ok('post page: content rendered server-side, scripts/handlers stripped', post.text.includes('<h2>First heading</h2>') && !post.text.includes('alert(1)') && !post.text.includes('onclick='))
ok('post page: single h1 + cover alt + related posts', (post.text.match(/<h1/g) || []).length >= 1 && post.text.includes('alt="Cover alt"') && post.text.includes('Keep reading') && post.text.includes('/blog/older-post/'))
ok('post page: shell robots meta replaced (indexable)', !post.text.includes('noindex, nofollow') || post.text.includes('index, follow'))
const hidden = await get('/blog/hidden-post/')
ok('noindex post carries noindex and is excluded from index/sitemap', hidden.text.includes('content="noindex, nofollow"') && !idx.text.includes('Hidden from search'))
for (const s of ['draft-post', 'scheduled-post', 'nope-nothing']) { const r = await get(`/blog/${s}/`); ok(`/blog/${s}/ is a 404 (noindex)`, r.status === 404 && r.text.includes('noindex')) }
const sm = await get('/sitemap.xml')
ok('sitemap: static pages + published posts, no drafts/noindex', sm.status === 200 && sm.text.includes('/about-us/') && sm.text.includes('/blog/') && sm.text.includes('/blog/welcome-post/') && !sm.text.includes('draft-post') && !sm.text.includes('scheduled-post') && !sm.text.includes('hidden-post') && sm.text.includes('<lastmod>'))
const rss = await get('/blog/rss.xml')
ok('RSS feed lists posts', rss.status === 200 && rss.text.includes('<rss') && rss.text.includes('A welcome post about portraits') && !rss.text.includes('Draft'))
ok('robots.txt references sitemap and blocks dashboard', (await get('/robots.txt')).text.includes('Disallow: /dashboard/'))

