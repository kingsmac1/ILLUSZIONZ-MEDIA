/* ── 1. blog rendered at the edge ── */
const past = new Date(Date.now() - 86400e3).toISOString()
const future = new Date(Date.now() + 5 * 86400e3).toISOString()
await rest('blog_posts', 'POST', [
  { slug: 'welcome-post', title: 'A welcome post about portraits', excerpt: 'An excerpt that explains the post in a hundred and twenty characters or so for the description meta tag, nice.', content: '<h2>First heading</h2><p>Hello <strong>world</strong> and a <a href="/contact/">link</a>.</p><script>alert(1)</script><p onclick="x()">Safe</p>', cover_url: '/images/ILU6151.webp', cover_alt: 'Cover alt', category: 'Tips', tags: ['portrait', 'tips'], published: true, published_at: past, seo_title: 'Custom SEO Title | Illuszionz', seo_description: 'Custom meta description for the welcome post.', og_image: '', read_minutes: 2 },
  { slug: 'older-post', title: 'An older post', excerpt: 'Older excerpt.', content: '<p>Old</p>', published: true, published_at: new Date(Date.now() - 9 * 86400e3).toISOString(), read_minutes: 1 },
  { slug: 'draft-post', title: 'Draft', content: '<p>d</p>', published: false },
  { slug: 'scheduled-post', title: 'Scheduled', content: '<p>s</p>', published: true, published_at: future },
  { slug: 'hidden-post', title: 'Hidden from search', content: '<p>h</p>', published: true, published_at: past, noindex: true },
])
const get = async (p) => { const r = await fetch(BASE + p); return { status: r.status, text: await r.text(), headers: r.headers } }
